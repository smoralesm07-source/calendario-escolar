CREATE TABLE public.school_alert_events (
 event_key text PRIMARY KEY,
 event_hash text NOT NULL,
 fecha date NOT NULL,
 curso text NOT NULL,
 asignatura text,
 descripcion text,
 origen text,
 active boolean NOT NULL DEFAULT true,
 first_seen_at timestamptz NOT NULL DEFAULT now(),
 last_seen_at timestamptz NOT NULL DEFAULT now(),
 changed_at timestamptz
);
CREATE INDEX idx_school_alert_events_active ON public.school_alert_events(active);
CREATE INDEX idx_school_alert_events_fecha ON public.school_alert_events(fecha);
CREATE TABLE public.school_alert_subscriptions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 email text NOT NULL UNIQUE,
 courses text[] NOT NULL DEFAULT ARRAY['3D'::text,'6B'::text],
 reminder_days integer[] NOT NULL DEFAULT ARRAY[3],
 notify_changes boolean NOT NULL DEFAULT true,
 status text NOT NULL DEFAULT 'pending',
 confirm_token_hash text,
 manage_token_hash text,
 token_expires_at timestamptz,
 confirmed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT school_alert_subscriptions_status_check
 CHECK (status=ANY(ARRAY['pending','active','unsubscribed']::text[]))
);
CREATE INDEX idx_school_alert_subscriptions_status ON public.school_alert_subscriptions(status);
CREATE TABLE public.school_alert_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscription_id uuid NOT NULL REFERENCES public.school_alert_subscriptions(id) ON DELETE CASCADE,
 event_key text NOT NULL,
 kind text NOT NULL,
 provider_message_id text,
 sent_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT school_alert_deliveries_subscription_id_event_key_kind_key
 UNIQUE (subscription_id,event_key,kind)
);
CREATE INDEX idx_school_alert_deliveries_subscription ON public.school_alert_deliveries(subscription_id);
CREATE FUNCTION public.school_alert_touch_updated_at() RETURNS trigger
 LANGUAGE plpgsql SET search_path TO 'public'
 AS $body$ BEGIN NEW.updated_at = now(); RETURN NEW; END; $body$;
CREATE TRIGGER trg_school_alert_touch_updated_at
 BEFORE UPDATE ON public.school_alert_subscriptions FOR EACH ROW
 EXECUTE FUNCTION public.school_alert_touch_updated_at();
